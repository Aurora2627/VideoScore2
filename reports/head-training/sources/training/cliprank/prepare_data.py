"""Prompt-disjoint score-head dataset preparation; no benchmark training."""
import argparse,collections,concurrent.futures,hashlib,json,re,time,unicodedata,urllib.request
from pathlib import Path
REV='99b9935b00a205756c25b0555f2dcdc071281327'
SEED=20261022
LABELS=('visual_quality','text_alignment','physical_consistency')
def read(p):return json.loads(Path(p).read_text(encoding='utf-8-sig'))
def save(p,x):
 p=Path(p);p.parent.mkdir(parents=True,exist_ok=True);tmp=p.with_suffix(p.suffix+'.tmp');tmp.write_text(json.dumps(x,ensure_ascii=False,indent=2),encoding='utf-8');tmp.replace(p)
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def key(s):return hashlib.sha256((str(SEED)+'|'+s).encode()).hexdigest()
def canonical(s):return ''.join(c for c in unicodedata.normalize('NFKC',s).casefold() if c.isalnum())
def parse_train(row):
 marker='Here we provide an AI video generated by text-to-video models and its text prompt:';ending='Based on the video content and the dimension definitions'
 assert row['problem'].count(marker)==1 and row['problem'].count(ending)==1
 prompt=row['problem'].split(marker)[1].split(ending)[0].strip().rstrip('.')
 numbers=re.findall('[1-5]',row['solution']);assert len(numbers)==3
 name=row['problem_id'];assert re.fullmatch('[0-9]{6}_[A-Za-z]',name)
 return {'video_name':name,'prompt':prompt,'prompt_id':name.split('_')[0],'ground_truth':dict(zip(LABELS,map(int,numbers))),'source_split':'official_train'}
def partition(train,bench,old_names,train_groups=128,val_groups=32,test_groups=48,max_candidates=6):
 test_ids={r['video_name'].split('_')[0] for r in bench};test_prompts={canonical(r['prompt']) for r in bench};groups=collections.defaultdict(list)
 for row in train:
  if row['prompt_id'] not in test_ids and canonical(row['prompt']) not in test_prompts:groups[row['prompt_id']].append(row)
 parents={k:k for k in groups}
 def find(k):
  while parents[k]!=k:parents[k]=parents[parents[k]];k=parents[k]
  return k
 seen={}
 for pid,rows in groups.items():
  for row in rows:
   c=canonical(row['prompt'])
   if c in seen:parents[find(pid)]=find(seen[c])
   seen[c]=pid
 merged=collections.defaultdict(list)
 for pid,rows in groups.items():merged[find(pid)].extend(rows)
 ids=sorted(merged,key=key);assert len(ids)>=train_groups+val_groups;splits={}
 for name,chosen in [('train',ids[:train_groups]),('validation',ids[train_groups:train_groups+val_groups])]:
  splits[name]=[dict(row,group_id=pid,split=name) for pid in chosen for row in sorted(merged[pid],key=lambda x:key(x['video_name']))[:max_candidates]]
 old_ids={n.split('_')[0] for n in old_names};old_prompts={canonical(r['prompt']) for r in bench if r['video_name'] in old_names};fresh=collections.defaultdict(list)
 for row in bench:
  pid=row['video_name'].split('_')[0]
  if pid not in old_ids and canonical(row['prompt']) not in old_prompts:fresh[pid].append(row)
 ids=sorted(fresh,key=lambda pid:(-int(len(fresh[pid])>1),key(pid)));assert len(ids)>=test_groups
 splits['test']=[dict(video_name=r['video_name'],prompt=r['prompt'],prompt_id=pid,group_id=pid,split='test',source_split='official_test',video_url=r['video_url'],ground_truth=dict(zip(LABELS,(r['visual_score'],r['t2v_score'],r['phy_score'])))) for pid in ids[:test_groups] for r in fresh[pid]]
 for a,b in [('train','validation'),('train','test'),('validation','test')]:
  assert not ({r['prompt_id'] for r in splits[a]} & {r['prompt_id'] for r in splits[b]})
  assert not ({canonical(r['prompt']) for r in splits[a]} & {canonical(r['prompt']) for r in splits[b]})
 return splits
def download(row,folder):
 import cv2
 path=folder/'videos'/(row['video_name']+'.mp4');receipt=path.with_suffix('.receipt.json');path.parent.mkdir(exist_ok=True)
 if path.exists():assert receipt.exists() and read(receipt)['sha256']==sha(path),'Unverified cached video'
 else:
  error=None
  for attempt in range(3):
   try:
    opener=urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(row['video_url'],timeout=45) as response:raw=response.read(64*1024*1024+1)
    assert 0<len(raw)<=64*1024*1024
    temp=path.with_suffix('.part');temp.write_bytes(raw);temp.replace(path);save(receipt,{'url':row['video_url'],'sha256':sha(path),'bytes':len(raw)});break
   except Exception as exc:error=exc;time.sleep(attempt+1)
  else:raise RuntimeError(row['video_name']+': '+str(error))
 cap=cv2.VideoCapture(str(path))
 try:ok,frame=cap.read();assert ok and frame is not None,'Undecodable video'
 finally:cap.release()
 return dict(row,video_path=str(path.resolve()),video_sha256=sha(path))
def main():
 ap=argparse.ArgumentParser();ap.add_argument('--data-dir',type=Path,default=Path('D:/career-projects/data/ClipRank-training'));ap.add_argument('--benchmark',type=Path,default=Path('D:/career-projects/data/VideoScoreBench-v2/metadata.json'));ap.add_argument('--download',action='store_true');a=ap.parse_args();a.data_dir.mkdir(exist_ok=True)
 rows=read(a.data_dir/'data_27k_train_RL.json');provenance=read(a.data_dir/'metadata-provenance.json');assert provenance['revision']==REV and sha(a.data_dir/'data_27k_train_RL.json')==provenance['sha256']
 bench=read(a.benchmark);generators=collections.defaultdict(set)
 for r in bench:generators[r['video_name'].split('_')[1]].add(r['video_url'].split('/')[-2])
 mapping={k:next(iter(v)) for k,v in generators.items() if len(v)==1};train=[];skipped=collections.Counter()
 for row in rows:
  r=parse_train(row);letter=r['video_name'].split('_')[1]
  if letter not in mapping:skipped[letter]+=1;continue
  start=int(r['prompt_id'])//500*500;r['video_url']='https://molar-public.oss-cn-hangzhou.aliyuncs.com/VideoScore/'+str(start).zfill(4)+'_'+str(start+499).zfill(4)+'/'+mapping[letter]+'/'+r['video_name']+'.mp4';r['url_provenance']='Derived from benchmark generator/directory mapping; actual bytes identified after download';train.append(r)
 root=Path(__file__).resolve().parents[2];old=set()
 for p in (root/'reports').rglob('manifest.json'):
  if 'head-training' in p.parts:continue
  data=read(p)
  if isinstance(data,dict):old.update(r['video_name'] for r in data.get('samples',[]) if 'video_name' in r)
 splits=partition(train,bench,old)
 plan={'revision':REV,'seed':SEED,'selection':'Hash-order prompt groups; train/validation from official_train; test from unused official_test, prioritizing multi-candidate groups without looking at scores','train_groups':128,'validation_groups':32,'test_groups':48,'max_train_validation_candidates_per_group':6,'excluded_previous_video_names':sorted(old),'excluded_ambiguous_generator_suffix_counts':dict(skipped),'generator_map':mapping,'metadata_sha256':provenance['sha256'],'benchmark_metadata_sha256':sha(a.benchmark),'counts':{k:len(v) for k,v in splits.items()}}
 plan_path=a.data_dir/'split-plan.json'
 if plan_path.exists():assert read(plan_path)==plan,'Existing plan differs; use a new data directory'
 else:save(plan_path,plan)
 save(a.data_dir/'planned-samples.json',{'splits':splits});print('SPLIT_PLAN',plan['counts'],'excluded_previous',len(old),flush=True)
 if not a.download:return
 ready=[];all_rows=[r for name in ('train','validation','test') for r in splits[name]]
 with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
  for item in pool.map(lambda row:download(row,a.data_dir),all_rows):
   ready.append(item)
   if len(ready)%25==0:print('VIDEOS_READY',len(ready),len(all_rows),flush=True)
 bysha=collections.defaultdict(set)
 for r in ready:bysha[r['video_sha256']].add(r['split'])
 assert all(len(v)==1 for v in bysha.values()),'Byte-identical video crosses splits'
 assert len(bysha)==len(ready),'Duplicate bytes require explicit plan review'
 save(a.data_dir/'manifest.json',{'samples':ready,'plan':plan,'purpose':'Frozen-backbone head training; no benchmark samples used in training/validation'});print('TRAINING_DATA_READY',len(ready),flush=True)
if __name__=='__main__':main()
